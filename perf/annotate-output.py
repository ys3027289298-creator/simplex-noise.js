#!/usr/bin/env python3
"""Add Chinese titles, axis labels and legends to the rendered output PNGs.

The noise textures and the timing curve are rendered by render-output.js using
the repository's pngjs dependency. PIL only draws the text overlay so the pixel
data itself stays generated by the library under test.
"""
import json
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'output')
FONT_PATH = '/mnt/c/Windows/Fonts/simhei.ttf'

def font(size):
    return ImageFont.truetype(FONT_PATH, size)

def titled(source, target, title):
    image = Image.open(os.path.join(OUT, source)).convert('RGB')
    bar_height = 56
    canvas = Image.new('RGB', (image.width, image.height + bar_height), (255, 255, 255))
    canvas.paste(image, (0, bar_height))
    draw = ImageDraw.Draw(canvas)
    draw.rectangle([0, 0, image.width, bar_height], fill=(245, 247, 250))
    draw.text((16, 14), title, fill=(20, 24, 32), font=font(26))
    canvas.save(os.path.join(OUT, target))

texture_titles = {
    'stone-cellular2D-f1.png': '2D 细胞噪声 F1（最近特征点距离）',
    'stone-cellular2D-f2-minus-f1.png': '2D 细胞噪声 F2-F1（石材胞腔边界）',
    'stone-cellular2D-manhattan.png': '2D 细胞噪声 曼哈顿距离 F1',
    'stone-cellular2D-chebyshev.png': '2D 细胞噪声 切比雪夫距离 F1',
    'stone-cellular2D-four-points.png': '2D 细胞噪声 每格 4 个特征点 F1',
    'stone-cellular3D-f1-slice.png': '3D 细胞噪声 F1（z=0.5 切片）',
    'comparison-simplex2D.png': '对照：单纯形噪声无法形成胞腔花纹',
}
for source, title in texture_titles.items():
    titled(source, source, title)

# Annotate the timing curve.
curve_path = os.path.join(OUT, 'feature-points-timing-curve.png')
chart = Image.open(curve_path).convert('RGB')
# add left padding so the rotated y axis label is not clipped
padding_left = 70
padded = Image.new('RGB', (chart.width + padding_left, chart.height), (255, 255, 255))
padded.paste(chart, (padding_left, 0))
chart = padded
draw = ImageDraw.Draw(chart)
title_font = font(30)
label_font = font(20)
small_font = font(17)
draw.text((chart.width // 2 - 250, 14), '特征点数量对单帧耗时的影响（256×256 固定网格）',
          fill=(16, 20, 28), font=title_font)
with open(os.path.join(OUT, 'benchmark-data.json'), encoding='utf-8') as handle:
    data = json.load(handle)
# axis labels
draw.text((chart.width // 2 - 150, chart.height - 40), '每格特征点数量 pointsPerCell',
          fill=(40, 44, 52), font=label_font)
vertical = '相对单纯形噪声的耗时倍数'
vy = chart.height // 2
for index, character in enumerate(vertical):
    draw.text((20, vy - 150 + index * 24), character, fill=(40, 44, 52), font=label_font)
# x axis tick values: the plot area starts at x=90 (plus the added padding)
# and spans 770 px in the original 900 px wide image.
plot_left = padding_left + 90
plot_width = 900 - 90 - 40
point_counts = [row['pointsPerCell'] for row in data['cellular2D']]
for points in point_counts:
    tick_x = plot_left + ((points - 1) / (point_counts[-1] - 1)) * plot_width
    draw.text((tick_x - 12, chart.height - 70), str(points), fill=(70, 74, 82), font=small_font)
# legend
legend_x, legend_y = chart.width - 260, 96
draw.rectangle([legend_x - 12, legend_y - 10, legend_x + 240, legend_y + 58],
               outline=(180, 184, 190), fill=(255, 255, 255))
draw.line([legend_x, legend_y, legend_x + 34, legend_y], fill=(38, 120, 210), width=4)
draw.text((legend_x + 44, legend_y - 12), '2D 细胞噪声', fill=(38, 120, 210), font=small_font)
draw.line([legend_x, legend_y + 30, legend_x + 34, legend_y + 30], fill=(210, 90, 60), width=4)
draw.text((legend_x + 44, legend_y + 18), '3D 细胞噪声', fill=(210, 90, 60), font=small_font)
# value labels on the default (single point) entries
for rows, color in ((data['cellular2D'], (38, 120, 210)),
                    (data['cellular3D'], (210, 90, 60))):
    first = rows[0]
    draw.text((padding_left + 300, 478 if rows is data['cellular2D'] else 448),
              f"默认 pointsPerCell=1：{first['ratioToSimplex']:.2f}x",
              fill=color, font=small_font)
chart.save(curve_path)
print('annotated output PNGs in', OUT)
